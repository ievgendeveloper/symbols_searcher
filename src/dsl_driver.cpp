/*
 * dsl_driver.cpp — connects re2c lexer to Lemon parser.
 *
 * The Lemon-generated parser exposes three functions:
 *   void* SymfindParseAlloc(void*(*)(size_t));
 *   void  SymfindParseFree(void*, void(*)(void*));
 *   void  SymfindParse(void*, int token_type, Token token, ParserContext*);
 *
 * (The "SymfindParse" prefix comes from `%name SymfindParse` in
 *  the grammar.)
 *
 * Our driver:
 *   1. Tokenizes the input via re2c-generated Lexer
 *   2. Allocates a Lemon parser instance
 *   3. Feeds tokens one by one until EOF
 *   4. Returns the constructed Rule (or nullopt on error)
 */

#include "symfind/dsl_lexer.h"
#include "symfind/dsl_parser.h"

#include <cstdlib>
#include <spdlog/spdlog.h>

/*
 * Forward-declare Lemon-generated parser interface.
 * grammar.c is compiled as C++ in our CMake setup (because the
 * %include block in grammar.y uses STL types), so no extern "C"
 * is needed — both sides use C++ linkage.
 */
void* SymfindParseAlloc(void* (*mallocProc)(size_t));
void SymfindParseFree(void* p, void (*freeProc)(void*));
void SymfindParse(void* yyp, int yymajor,
                  symfind::dsl::Token yyminor,
                  symfind::dsl::ParserContext* ctx);

/* Token type IDs from grammar.h (generated by Lemon).
   Each token gets a #define TK_xxx <int>. We need to map our
   TokenType enum values to these integers when feeding the parser.

   Rather than including grammar.h here directly (which would create
   a circular include between the public dsl_parser.h and the
   generated header), we include it locally and translate. */
#include "grammar.h" // generated by Lemon; in build/dsl/

namespace symfind::dsl
{

    /// Translate our TokenType enum to Lemon-generated TK_xxx IDs.
    static int token_type_to_id(TokenType t)
    {
        switch (t)
        {
        case TokenType::Find:
            return TK_FIND;
        case TokenType::Function:
            return TK_FUNCTION;
        case TokenType::Global:
            return TK_GLOBAL;
        case TokenType::In:
            return TK_IN;
        case TokenType::Where:
            return TK_WHERE;
        case TokenType::Calls:
            return TK_CALLS;
        case TokenType::CalledBy:
            return TK_CALLED_BY;
        case TokenType::ReferencedBy:
            return TK_REFERENCED_BY;
        case TokenType::Exported:
            return TK_EXPORTED;
        case TokenType::Not:
            return TK_NOT;
        case TokenType::HasLoop:
            return TK_HAS_LOOP;
        case TokenType::Take:
            return TK_TAKE;
        case TokenType::First:
            return TK_FIRST;
        case TokenType::Count:
            return TK_COUNT;
        case TokenType::Xrefs:
            return TK_XREFS;
        case TokenType::StackFrameSize:
            return TK_STACK_FRAME_SIZE;
        case TokenType::CallsCount:
            return TK_CALLS_COUNT;
        case TokenType::ReadsReg:
            return TK_READS_REG;
        case TokenType::String:
            return TK_STRING;
        case TokenType::Integer:
            return TK_INTEGER;
        case TokenType::Gte:
            return TK_GTE;
        case TokenType::Lte:
            return TK_LTE;
        case TokenType::Eq:
            return TK_EQ;
        case TokenType::Gt:
            return TK_GT;
        case TokenType::Lt:
            return TK_LT;
        case TokenType::LParen:
            return TK_LPAREN;
        case TokenType::RParen:
            return TK_RPAREN;
        case TokenType::Semi:
            return TK_SEMI;
        case TokenType::Eof:
            return 0; // Lemon convention
        case TokenType::Error:
            return -1; // signals error
        }
        return -1;
    }

    std::optional<Rule> DslParser::parse(std::string_view source)
    {
        // 1. Tokenize
        Lexer lexer(source);

        // 2. Allocate Lemon parser
        void* parser = SymfindParseAlloc(std::malloc);
        if (!parser)
        {
            SPDLOG_ERROR("Failed to allocate Lemon parser");
            return std::nullopt;
        }

        ParserContext ctx;

        // 3. Feed tokens one by one
        while (true)
        {
            Token t = lexer.next();

            if (t.type == TokenType::Error)
            {
                SPDLOG_ERROR("Lexer error at line {}:{}: '{}'",
                             t.line, t.column, t.str_value);
                ctx.had_error = true;
                break;
            }

            if (t.type == TokenType::Eof)
            {
                // Signal end-of-input to Lemon (token id = 0)
                SymfindParse(parser, 0, t, &ctx);
                break;
            }

            int id = token_type_to_id(t.type);
            SymfindParse(parser, id, std::move(t), &ctx);

            if (ctx.had_error)
            {
                SPDLOG_ERROR("Parse error near line {}", ctx.error_line);
                break;
            }
        }

        // 4. Cleanup
        SymfindParseFree(parser, std::free);

        if (ctx.had_error)
        {
            return std::nullopt;
        }

        if (ctx.result.predicates.empty())
        {
            SPDLOG_ERROR("Rule must have at least one predicate");
            return std::nullopt;
        }

        return std::move(ctx.result);
    }

} // namespace symfind::dsl
